import { BlockRole, POICategory } from './types';

export type LangCode = 'zh' | 'en' | 'ja';

const savedLang = (typeof localStorage !== 'undefined' && localStorage.getItem('levelforge_lang')) as LangCode | null;
let currentLang: LangCode = savedLang === 'en' || savedLang === 'ja' ? savedLang : 'zh';

export function getLang(): LangCode {
  return currentLang;
}

export function setLang(lang: LangCode): void {
  currentLang = lang;
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('levelforge_lang', lang);
  }
}

